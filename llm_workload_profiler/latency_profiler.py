"""
Latency Profiler Module for LLM Inference Workloads.

Part of Member 1: Workload Simulation & Latency Profiling Module.
Project: LLM-Aware OS Scheduler for Local AI Inference Workloads.

This module profiles inference latency metrics:
- Time to First Token (TTFT)
- Inter-Token Latency (ITL) for every generated token
- Total generation duration
- Statistical metrics (Average, Median, p95, p99 ITL)

IMPORTANT NOTICE:
All values generated by default are SIMULATED and explicitly tagged as `is_simulated = True`.
They must never be presented as real physical hardware benchmarks.
An adapter interface (`InferenceBackend`) is provided so a real local LLM engine
(e.g., llama.cpp, Ollama, ONNX Runtime) can be plugged in later.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
import math
import random
import statistics
import time
from typing import List, Optional

from workload_generator import InferenceRequest


@dataclass
class TokenLatencyRecord:
    """Detailed record of a single token generation event."""
    token_index: int
    timestamp_s: float
    inter_token_latency_ms: float
    is_simulated: bool = True


@dataclass
class RequestProfileResult:
    """Comprehensive latency profile result for an inference request."""
    request_id: str
    is_simulated: bool
    data_source: str
    submission_timestamp_s: float
    ttft_ms: float
    total_generation_time_ms: float
    total_tokens_generated: int
    token_records: List[TokenLatencyRecord] = field(default_factory=list)
    itl_samples_ms: List[float] = field(default_factory=list)
    avg_itl_ms: float = 0.0
    median_itl_ms: float = 0.0
    p95_itl_ms: float = 0.0
    p99_itl_ms: float = 0.0

    def to_summary_dict(self) -> dict:
        """Serializes high-level summary metrics to a dictionary."""
        return {
            "request_id": self.request_id,
            "is_simulated": self.is_simulated,
            "data_source": self.data_source,
            "submission_timestamp_s": round(self.submission_timestamp_s, 4),
            "ttft_ms": round(self.ttft_ms, 2),
            "total_generation_time_ms": round(self.total_generation_time_ms, 2),
            "total_tokens_generated": self.total_tokens_generated,
            "avg_itl_ms": round(self.avg_itl_ms, 2),
            "median_itl_ms": round(self.median_itl_ms, 2),
            "p95_itl_ms": round(self.p95_itl_ms, 2),
            "p99_itl_ms": round(self.p99_itl_ms, 2),
        }


def calculate_percentile(data: List[float], percentile: float) -> float:
    """Calculates the specified percentile (0-100) using linear interpolation."""
    if not data:
        return 0.0
    if len(data) == 1:
        return data[0]

    sorted_data = sorted(data)
    # Using Nearest Rank or standard percentile formula
    k = (len(sorted_data) - 1) * (percentile / 100.0)
    floor_k = math.floor(k)
    ceil_k = math.ceil(k)

    if floor_k == ceil_k:
        return sorted_data[int(k)]
    d0 = sorted_data[floor_k] * (ceil_k - k)
    d1 = sorted_data[ceil_k] * (k - floor_k)
    return d0 + d1


class InferenceBackend(ABC):
    """Abstract interface for inference engines.
    
    Allows swapping between simulated inference and real local model execution
    (e.g., llama-cpp-python, vLLM, transformers) without altering the profiler logic.
    """

    @abstractmethod
    def run_inference(
        self,
        request: InferenceRequest,
        interference_factor: float = 1.0,
    ) -> RequestProfileResult:
        """Executes inference and returns latency profile data."""
        pass


class SimulatedInferenceBackend(InferenceBackend):
    """Simulates LLM inference latency realistically based on prefill + decoding dynamics.
    
    Prefill duration (TTFT) scales with prompt token length.
    Inter-token latency (ITL) reflects autoregressive token decoding with realistic jitter
    and configurable background interference multipliers.
    """

    def __init__(self, seed: Optional[int] = 42):
        self.rng = random.Random(seed)

    def run_inference(
        self,
        request: InferenceRequest,
        interference_factor: float = 1.0,
    ) -> RequestProfileResult:
        """Generates simulated latency measurements for a given inference request."""
        submission_time = request.arrival_time_s

        # TTFT (Prefill Phase): Scales with prompt length + baseline overhead + interference
        # Baseline: ~0.15 ms per prompt token on typical simulated small model + jitter
        prefill_per_token_ms = 0.18 * interference_factor
        prefill_jitter_ms = self.rng.uniform(-3.0, 5.0)
        base_ttft_ms = 35.0 * interference_factor
        simulated_ttft_ms = max(5.0, base_ttft_ms + (request.prompt_tokens * prefill_per_token_ms) + prefill_jitter_ms)

        # Autoregressive Decoding Phase (ITL per output token)
        # Base ITL is centered near the request's target ITL, perturbed by interference and normal jitter
        base_itl_mean = request.target_itl_ms * interference_factor
        
        token_records: List[TokenLatencyRecord] = []
        itl_samples: List[float] = []

        # Current simulated timeline
        current_time_s = submission_time + (simulated_ttft_ms / 1000.0)

        for token_idx in range(1, request.output_tokens + 1):
            # Realistic latency variation: Gaussian jitter with occasional tail spikes (e.g., GC/cache miss)
            jitter_ms = self.rng.gauss(0.0, 3.5 * interference_factor)
            spike_ms = 0.0
            # 3% chance of a tail latency spike
            if self.rng.random() < 0.03:
                spike_ms = self.rng.uniform(15.0, 45.0) * interference_factor

            simulated_itl_ms = max(2.0, base_itl_mean + jitter_ms + spike_ms)
            itl_samples.append(round(simulated_itl_ms, 3))

            current_time_s += (simulated_itl_ms / 1000.0)
            token_records.append(
                TokenLatencyRecord(
                    token_index=token_idx,
                    timestamp_s=round(current_time_s, 5),
                    inter_token_latency_ms=round(simulated_itl_ms, 3),
                    is_simulated=True,
                )
            )

        # Compute summary statistics
        total_gen_ms = simulated_ttft_ms + sum(itl_samples)
        avg_itl = statistics.mean(itl_samples) if itl_samples else 0.0
        median_itl = statistics.median(itl_samples) if itl_samples else 0.0
        p95_itl = calculate_percentile(itl_samples, 95.0)
        p99_itl = calculate_percentile(itl_samples, 99.0)

        return RequestProfileResult(
            request_id=request.request_id,
            is_simulated=True,
            data_source="SimulatedInferenceBackend (Synthetic Model)",
            submission_timestamp_s=submission_time,
            ttft_ms=round(simulated_ttft_ms, 3),
            total_generation_time_ms=round(total_gen_ms, 3),
            total_tokens_generated=request.output_tokens,
            token_records=token_records,
            itl_samples_ms=itl_samples,
            avg_itl_ms=round(avg_itl, 3),
            median_itl_ms=round(median_itl, 3),
            p95_itl_ms=round(p95_itl, 3),
            p99_itl_ms=round(p99_itl, 3),
        )


class RealModelAdapter(InferenceBackend):
    """Adapter template for integrating a real local LLM runtime (e.g., llama.cpp / Ollama).
    
    When configured with a real runtime, records physical wall-clock timestamps.
    """

    def __init__(self, model_path: Optional[str] = None):
        self.model_path = model_path

    def run_inference(
        self,
        request: InferenceRequest,
        interference_factor: float = 1.0,
    ) -> RequestProfileResult:
        """Placeholder for real inference execution."""
        raise NotImplementedError(
            "RealModelAdapter requires a configured local runtime (e.g., llama.cpp or Ollama). "
            "Use SimulatedInferenceBackend for simulation-based profiling."
        )


class LatencyProfiler:
    """Coordinates latency profiling of inference workloads using the configured backend."""

    def __init__(self, backend: Optional[InferenceBackend] = None):
        self.backend = backend if backend is not None else SimulatedInferenceBackend()

    def profile_request(
        self,
        request: InferenceRequest,
        interference_factor: float = 1.0,
    ) -> RequestProfileResult:
        """Profiles a single inference request."""
        return self.backend.run_inference(request, interference_factor=interference_factor)

    def profile_workload(
        self,
        requests: List[InferenceRequest],
        interference_factor: float = 1.0,
    ) -> List[RequestProfileResult]:
        """Profiles a sequence of requests."""
        results: List[RequestProfileResult] = []
        for req in requests:
            result = self.profile_request(req, interference_factor=interference_factor)
            results.append(result)
        return results


