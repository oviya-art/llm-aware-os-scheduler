SCHEDULERS = ["fcfs", "rr", "priority", "cfs", "edf", "token_laxity"]
SCHEDULER_LABELS = {
    "fcfs": "FCFS", "rr": "Round Robin", "priority": "Static Priority",
    "cfs": "CFS-like", "edf": "EDF (ablation)", "token_laxity": "Token-Laxity (TLS)",
}
NOVEL = "token_laxity"
BASELINES = [s for s in SCHEDULERS if s != NOVEL]

# TLS ablation variants (each disables ONE ingredient of the algorithm)
TLS_VARIANTS: Dict[str, Dict[str, Any]] = {
    "tls_full":        {},
    "tls_no_planner":  {"util_bound": 1000.0},                       # no capacity planner -> pure laxity order
    "tls_no_midtoken": {"margin_hard": 1e9},                         # never preempt mid-token
    "tls_no_aging":    {"bg_aging_per_s": 0.0, "starve_limit_ms": 1e12},  # no starvation guard
}


def make_scheduler(name: str, quantum_ms: float = 20.0, **tls_overrides) -> Any:
    if name == "fcfs":
        return FCFSScheduler()
    if name == "rr":
        return RoundRobinScheduler(quantum_ms)
    if name == "priority":
        return PriorityScheduler(quantum_ms)
    if name == "cfs":
        return CFSLikeScheduler()
    if name == "edf":
        return EDFScheduler()
    if name == "token_laxity":
        return TokenLaxityScheduler(**tls_overrides)
    if name in TLS_VARIANTS:
        s = TokenLaxityScheduler(**{**TLS_VARIANTS[name], **tls_overrides})
        s.name = name
        return s
    raise ValueError(f"unknown scheduler {name!r}")


# --------------------------------------------------------------------------- scenarios
@dataclass(frozen=True)
class Scenario:
    key: str
    title: str
    blurb: str
    m1_scenario: str          # Member 1 LoadScenario (latency interference model)
    requests: int             # inference requests generated by Member 1
    arrival_rps: float
    background: str           # Member 2 background scenario (real competing CPU jobs)
    cores: int
    bg_fraction: Optional[float] = None


SCENARIOS: Dict[str, Scenario] = {s.key: s for s in [
    Scenario("light", "Light load", "A few chat requests, almost idle machine.",
             "light_load", 6, 0.6, "light_load", 4),
    Scenario("mixed", "Mixed CPU + inference", "Bursty compile/IO jobs next to steady chat traffic.",
             "mixed_load", 10, 1.0, "mixed_load", 4),
    Scenario("heavy", "Heavy load", "Many concurrent users and sustained CPU-bound jobs.",
             "heavy_load", 14, 1.4, "heavy_load", 4),
    Scenario("stress", "Overload stress", "Background jobs take ~70% of the machine on top of heavy chat load.",
             "heavy_load", 14, 1.4, "heavy_load", 4, 0.70),
    Scenario("tenant", "Multi-tenant (8 cores)", "More users, more cores, bursty neighbours.",
             "mixed_load", 24, 2.0, "mixed_load", 8),
]}


@dataclass
class Workload:
    scenario: Scenario
    seed: int
    trace_path: str
    loaded: LoadedTrace
    tasks: List[Task]
    bg_count: int
    offered_load: float       # (inference + background) CPU demand / machine capacity over the arrival horizon


def build_workload(sc: Scenario, seed: int, trace_dir: str, *, cores: Optional[int] = None,
                   requests: Optional[int] = None, arrival_rps: Optional[float] = None,
                   background: Optional[str] = None, bg_fraction: Optional[float] = None,
                   m1_scenario: Optional[str] = None, tag: Optional[str] = None) -> Workload:
    """Member 1 generates + profiles a trace, Member 2's loader turns it into tasks."""
    cores = cores or sc.cores
    requests = requests or sc.requests
    rps = arrival_rps or sc.arrival_rps
    background = background or sc.background
    m1_scn = m1_scenario or sc.m1_scenario
    frac = sc.bg_fraction if bg_fraction is None else bg_fraction

    os.makedirs(trace_dir, exist_ok=True)
    res = MixedWorkloadRunner(seed=seed).run_scenario(LoadScenario(m1_scn), requests, rps)
    name = tag or f"{sc.key}_s{seed}"
    path = TraceExporter(trace_dir).export_json(
        name, res.requests, res.profiles, res.evaluations,
        experiment_config={"mode": "simulation", "scenario": m1_scn, "seed": seed,
                           "requests_count": requests, "arrival_rate_rps": rps,
                           "avg_interference_factor": res.interference_factor, "is_simulated": True})
    loaded = load_trace(path, LoadOptions())
    bg = generate_background(background, cores, loaded.horizon_ms, seed=seed + 1, fraction_override=frac)
    tasks = loaded.tasks + bg
    arrival_span = max((t.arrival_ms for t in loaded.tasks), default=1.0) + 1.0
    demand = sum(t.total_service_ms for t in tasks)
    horizon = max(loaded.horizon_ms, arrival_span)
    return Workload(sc, seed, path, loaded, tasks, len(bg), demand / (horizon * cores))


def simulate(tasks: List[Task], scheduler_name: str, cores: int, quantum_ms: float = 20.0,
             **tls_overrides) -> SimulationResult:
    return Simulator(tasks, make_scheduler(scheduler_name, quantum_ms, **tls_overrides),
                     SimConfig(num_cores=cores)).run()
