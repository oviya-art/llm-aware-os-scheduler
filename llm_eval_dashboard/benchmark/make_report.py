"""Builds results/figures/*.png and results/REPORT.md (the evaluation section) from results/summary.json."""
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from benchmark.common import ROOT, SCHEDULER_LABELS as LAB, SCHEDULERS   # noqa: E402

RES = os.path.join(ROOT, "results")
FIG = os.path.join(RES, "figures")
COL = {"fcfs": "#8794A3", "rr": "#C27B2C", "priority": "#8B6BB5", "cfs": "#B5546E", "edf": "#2E9AA8", "token_laxity": "#0B5FFF"}
SHORT = {"fcfs": "FCFS", "rr": "RR", "priority": "Priority", "cfs": "CFS", "edf": "EDF", "token_laxity": "TLS"}


def main():
    b = json.load(open(os.path.join(RES, "summary.json")))
    os.makedirs(FIG, exist_ok=True)
    sc = list(b["scenarios"])
    S = lambda k, s, m: b["summary"][k][s][m]["mean"]
    E = lambda k, s, m: (b["summary"][k][s][m]["hi"] - b["summary"][k][s][m]["lo"]) / 2

    def grouped(metric, ylabel, fname, title):
        fig, ax = plt.subplots(figsize=(9, 4.2))
        w = 0.13
        for i, s in enumerate(SCHEDULERS):
            ax.bar([j + (i - 2.5) * w for j in range(len(sc))], [S(k, s, metric) for k in sc], w,
                   yerr=[E(k, s, metric) for k in sc], color=COL[s], label=LAB[s], capsize=2)
        ax.set_xticks(range(len(sc)))
        ax.set_xticklabels([b["scenarios"][k]["title"] for k in sc], fontsize=8)
        ax.set_ylabel(ylabel)
        ax.set_title(title, loc="left", fontweight="bold")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(fontsize=7, ncol=3, frameon=False)
        fig.tight_layout()
        fig.savefig(os.path.join(FIG, fname), dpi=160)
        plt.close(fig)

    grouped("request_miss_rate", "% of requests violating SLA", "fig1_request_sla.png", "Request-level SLA violations (lower is better)")
    grouped("token_miss_rate", "% of tokens late", "fig2_token_miss.png", "Token deadline-miss rate (lower is better)")
    grouped("p99_itl_ms", "ms", "fig3_p99_itl.png", "p99 inter-token latency (lower is better)")
    grouped("jain_progress", "Jain index", "fig4_fairness.png", "Jain fairness on normalised progress (higher is better)")
    grouped("bg_mean_slowdown", "x slowdown", "fig5_bg_cost.png", "Cost: background job slowdown (lower is better)")

    fig, ax = plt.subplots(figsize=(6, 4.5))
    for s in SCHEDULERS:
        ax.scatter([S(k, s, "bg_mean_slowdown") for k in sc], [S(k, s, "request_miss_rate") for k in sc], c=COL[s],
                   s=90 if s == "token_laxity" else 40, edgecolor="k" if s == "token_laxity" else "none", label=LAB[s])
    ax.set_xlabel("background slowdown (x)")
    ax.set_ylabel("% requests violating SLA")
    ax.set_title("Quality vs cost trade-off", loc="left", fontweight="bold")
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=7, frameon=False)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "fig6_tradeoff.png"), dpi=160)
    plt.close(fig)

    # ------------------------------------------------------------------ markdown
    L = ["# Performance evaluation (Member 3)", "",
         "All numbers are generated by `python -m benchmark.run_benchmark` and written to `results/`. "
         "Each scenario is replicated over independent random seeds; every seed produces a fresh Member 1 trace and fresh background jobs, "
         "and all six schedulers run on exactly the same task set (paired design). Values are means with 95% t-intervals.", "",
         "## Scenarios", "", "| Scenario | Requests | Rate (req/s) | Cores | Background | Offered load | Seeds |", "|---|---|---|---|---|---|---|"]
    for k in sc:
        m = b["scenarios"][k]
        bg = m["background"] + (f" ({int(m['bg_fraction'] * 100)}%)" if m["bg_fraction"] else "")
        L.append(f"| {m['title']} | {m['requests']} | {m['arrival_rps']} | {m['cores']} | {bg} | {m['offered_load']:.2f} | {m['seeds']} |")
    L += ["", "Offered load = total CPU demand (chat plus background) divided by machine capacity over the arrival horizon; above 1 the machine is overloaded.", ""]

    def table(metric, label, dec=1, unit=""):
        out = [f"### {label}", "", "| Scheduler | " + " | ".join(b["scenarios"][k]["title"] for k in sc) + " |", "|---|" + "---|" * len(sc)]
        for s in SCHEDULERS:
            cells = []
            best = min if not b["metric_meta"][metric]["higher_better"] else max
            for k in sc:
                v = S(k, s, metric)
                bv = best(S(k, x, metric) for x in SCHEDULERS)
                t = f"{v:.{dec}f}{unit} ±{E(k, s, metric):.{dec}f}"
                cells.append(f"**{t}**" if abs(v - bv) < 1e-9 else t)
            out.append(f"| {LAB[s]} | " + " | ".join(cells) + " |")
        return out + [""]

    L += ["## Results by scenario", ""]
    L += table("request_miss_rate", "Request SLA-violation rate (%), lower is better", 1)
    L += table("token_miss_rate", "Token deadline-miss rate (%), lower is better", 2)
    L += table("avg_token_latency_ms", "Average token latency (ms), lower is better", 1)
    L += table("p99_itl_ms", "p99 inter-token latency (ms), lower is better", 0)
    L += table("throughput_tok_s", "Decode throughput (tokens/s), higher is better", 1)
    L += table("jain_progress", "Jain fairness index on normalised progress, higher is better", 3)
    L += table("bg_mean_slowdown", "Background job slowdown (x), lower is better", 2)

    L += ["## Statistical comparison (TLS against each baseline)", "",
          "Paired by seed. Improvement is relative to the baseline mean, positive means TLS is better. p-values are two-sided Wilcoxon "
          "signed-rank tests, Holm-corrected over the five baselines. `ALL` pools every scenario and seed.", ""]
    for metric in ("request_miss_rate", "token_miss_rate", "p99_itl_ms", "throughput_tok_s"):
        L += [f"### {b['metric_meta'][metric]['label']}", "", "| Baseline | Scenario | TLS | Baseline | Improvement | W / T / L | Cohen d | Holm p |", "|---|---|---|---|---|---|---|---|"]
        for c in b["comparisons"]:
            if c["metric"] != metric or c["scenario"] not in ("ALL", "heavy", "mixed"):
                continue
            imp = "n/a" if c["rel_improvement_pct"] is None else f"{c['rel_improvement_pct']:+.0f}%"
            p = "<0.001" if c["p_holm"] < 0.001 else f"{c['p_holm']:.3f}"
            L.append(f"| {SHORT[c['baseline']]} | {c['scenario']} | {c['mean_a']:.2f} | {c['mean_b']:.2f} | {imp} | {c['wins']}/{c['ties']}/{c['losses']} | {c['cohens_dz']:.2f} | {p}{'*' if c['significant'] else ''} |")
        L.append("")
    L += ["Full table for every scenario and metric: `results/comparisons.csv`.", ""]

    L += ["## Ablation of the TLS design", "", "| Scenario | Variant | Request SLA miss % | Token miss % | p99 ITL ms | Background slowdown |", "|---|---|---|---|---|---|"]
    names = {"tls_full": "full", "tls_no_planner": "no capacity planner", "tls_no_midtoken": "no mid-token preemption", "tls_no_aging": "no starvation guard"}
    for k, v in b["ablation"].items():
        for var, m in v.items():
            L.append(f"| {k} | {names[var]} | {m['request_miss_rate']['mean']:.1f} | {m['token_miss_rate']['mean']:.2f} | {m['p99_itl_ms']['mean']:.0f} | {m['bg_mean_slowdown']['mean']:.2f} |")
    L += ["", "## Discussion", ""]
    h = lambda s, m: S("heavy", s, m)
    L += [
        f"1. **Chat quality.** In the heavy scenario TLS leaves {h('token_laxity','request_miss_rate'):.0f}% of requests violating their SLA, against "
        f"{h('rr','request_miss_rate'):.0f}% for Round Robin, {h('cfs','request_miss_rate'):.0f}% for the CFS-like scheduler, {h('priority','request_miss_rate'):.0f}% for static priority, "
        f"{h('fcfs','request_miss_rate'):.0f}% for FCFS and {h('edf','request_miss_rate'):.0f}% for EDF. Pooled over all scenarios the improvement is significant against every baseline after Holm correction.",
        f"2. **Where TLS does not win.** FCFS has a lower raw token-late rate ({h('fcfs','token_miss_rate'):.1f}% vs {h('token_laxity','token_miss_rate'):.1f}%) and lower p99 gap, because it never interleaves requests: "
        "tokens flow smoothly once a request starts, but requests wait in a queue for their first token. The token-level rate counts that wait as a single miss. "
        "This is why we also report the request-level SLA rate.",
        f"3. **Cost.** TLS makes background jobs {h('token_laxity','bg_mean_slowdown'):.1f}x slower in the heavy scenario (static priority {h('priority','bg_mean_slowdown'):.1f}x, Round Robin {h('rr','bg_mean_slowdown'):.1f}x). "
        "That is the price of protecting streams; it is not hidden by the headline metric.",
        f"4. **Fairness and throughput.** TLS has the highest Jain index in every loaded scenario ({h('token_laxity','jain_progress'):.3f} heavy). Throughput matches EDF and is about "
        f"{100 * (h('token_laxity','throughput_tok_s') / h('rr','throughput_tok_s') - 1):.0f}% above Round Robin in the heavy scenario, because RR and CFS waste work on late tokens and context switches.",
        "5. **Design ablation.** The capacity planner is the component that matters. Mid-token preemption showed no measurable effect in these workloads, and the starvation guard trades a small inference penalty for background fairness.",
        "", "## Threats to validity", "",
        "- Everything is simulated. CPU time is modelled; memory-bandwidth and cache contention are not.",
        "- Member 1's traces are synthetic and scaled by Member 2's headroom constant (0.7 of the SLA target); results depend on that calibration.",
        "- The CFS-like baseline is a simplified vruntime model, not the Linux kernel scheduler.",
        "- Scenario parameters were chosen to span load levels, not tuned to favour any scheduler; TLS parameters are Member 2's defaults.", ""]
    open(os.path.join(RES, "REPORT.md"), "w").write("\n".join(L))
    print("wrote", os.path.join(RES, "REPORT.md"))


if __name__ == "__main__":
    main()
